package store

import (
	"database/sql"
	"encoding/json"
	"errors"
	"time"
)

// MFA holds a user's two-factor state. Secret is empty when MFA is off.
type MFA struct {
	Secret        string
	Pending       string // a secret being set up, not yet confirmed with a code
	LastStep      int64  // the newest TOTP time step accepted (replay guard)
	RecoveryCodes []string
}

// GetMFA returns the user's two-factor state, or (nil, nil) for no such user.
func (s *Store) GetMFA(userID int64) (*MFA, error) {
	var m MFA
	var codes string
	err := s.read.QueryRow(
		`SELECT totp_secret, totp_pending, totp_last_step, recovery_codes FROM users WHERE id=?`, userID).
		Scan(&m.Secret, &m.Pending, &m.LastStep, &codes)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	if codes != "" {
		if err := json.Unmarshal([]byte(codes), &m.RecoveryCodes); err != nil {
			return nil, err
		}
	}
	return &m, nil
}

// MFAEnabledUsers returns the ids of users with two-factor sign-in on.
func (s *Store) MFAEnabledUsers() (map[int64]bool, error) {
	rows, err := s.read.Query(`SELECT id FROM users WHERE totp_secret <> ''`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := map[int64]bool{}
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			return nil, err
		}
		out[id] = true
	}
	return out, rows.Err()
}

// SetTOTPPending stores a secret being set up; it takes effect only through
// EnableTOTP, after the user proves their app has it.
func (s *Store) SetTOTPPending(userID int64, secret string) error {
	_, err := s.db.Exec(`UPDATE users SET totp_pending=?, updated_at=? WHERE id=?`, secret, time.Now().Unix(), userID)
	return err
}

// EnableTOTP makes the pending secret the active one, provided it is still the
// one the user confirmed (a second setup started meanwhile wins otherwise), and
// stores the recovery codes' hashes. step is the time step of the confirming
// code, recorded so that code can't sign in too. It reports whether it applied.
func (s *Store) EnableTOTP(userID int64, secret string, step int64, recoveryHashes []string) (bool, error) {
	codes, err := json.Marshal(recoveryHashes)
	if err != nil {
		return false, err
	}
	res, err := s.db.Exec(
		`UPDATE users SET totp_secret=?, totp_pending='', totp_last_step=?, recovery_codes=?, updated_at=?
		 WHERE id=? AND totp_pending=? AND totp_pending <> ''`,
		secret, step, string(codes), time.Now().Unix(), userID, secret)
	if err != nil {
		return false, err
	}
	n, err := res.RowsAffected()
	return n == 1, err
}

// DisableTOTP turns two-factor sign-in off and forgets every part of it.
func (s *Store) DisableTOTP(userID int64) error {
	_, err := s.db.Exec(
		`UPDATE users SET totp_secret='', totp_pending='', totp_last_step=0, recovery_codes='', updated_at=? WHERE id=?`,
		time.Now().Unix(), userID)
	return err
}

// UseTOTPStep records step as used if it is newer than the last one accepted,
// in one statement, so the same code (or an older one) can't be used twice even
// by two requests racing. It reports whether the step was accepted.
func (s *Store) UseTOTPStep(userID int64, step int64) (bool, error) {
	res, err := s.db.Exec(
		`UPDATE users SET totp_last_step=? WHERE id=? AND totp_secret <> '' AND totp_last_step < ?`,
		step, userID, step)
	if err != nil {
		return false, err
	}
	n, err := res.RowsAffected()
	return n == 1, err
}

// UseRecoveryCode removes one recovery code by its hash. The list is swapped
// only if it is unchanged since read, so a code can't be spent twice by racing
// requests. It reports whether the code was there and is now spent, and how
// many remain.
func (s *Store) UseRecoveryCode(userID int64, hash string) (ok bool, left int, err error) {
	for attempt := 0; attempt < 3; attempt++ {
		var cur string
		err = s.db.QueryRow(`SELECT recovery_codes FROM users WHERE id=? AND totp_secret <> ''`, userID).Scan(&cur)
		if errors.Is(err, sql.ErrNoRows) {
			return false, 0, nil
		}
		if err != nil || cur == "" {
			return false, 0, err
		}
		var codes []string
		if err = json.Unmarshal([]byte(cur), &codes); err != nil {
			return false, 0, err
		}
		kept := codes[:0:0]
		for _, c := range codes {
			if c != hash {
				kept = append(kept, c)
			}
		}
		if len(kept) == len(codes) {
			return false, len(codes), nil
		}
		next, _ := json.Marshal(kept)
		res, err := s.db.Exec(`UPDATE users SET recovery_codes=? WHERE id=? AND recovery_codes=?`, string(next), userID, cur)
		if err != nil {
			return false, 0, err
		}
		if n, _ := res.RowsAffected(); n == 1 {
			return true, len(kept), nil
		}
		// Someone else changed the list meanwhile; read it again.
	}
	return false, 0, errors.New("recovery codes changed concurrently")
}

// SetRecoveryCodes replaces the recovery codes (regenerated by the user).
func (s *Store) SetRecoveryCodes(userID int64, hashes []string) error {
	codes, err := json.Marshal(hashes)
	if err != nil {
		return err
	}
	_, err = s.db.Exec(`UPDATE users SET recovery_codes=?, updated_at=? WHERE id=? AND totp_secret <> ''`,
		string(codes), time.Now().Unix(), userID)
	return err
}

// MFAChallenge is a password sign-in waiting for its second factor.
type MFAChallenge struct {
	UserID   int64
	Kind     string // "verify" (enter a code) or "setup" (enroll first)
	Attempts int
}

// CreateMFAChallenge stores a challenge under the token's hash, pruning expired
// ones on the way.
func (s *Store) CreateMFAChallenge(token string, userID int64, kind string, expiresAt int64) error {
	_, _ = s.db.Exec(`DELETE FROM mfa_challenges WHERE expires_at < ?`, time.Now().Unix())
	_, err := s.db.Exec(`INSERT INTO mfa_challenges(token, user_id, kind, attempts, expires_at) VALUES(?,?,?,0,?)`,
		hashSecret(token), userID, kind, expiresAt)
	return err
}

// MFAChallengeAttempt counts one attempt against the challenge and returns it,
// or nil when it is missing, expired, or out of attempts (it is then deleted).
// The count goes up before the code is checked, so a parallel burst can't get
// more than maxAttempts guesses.
func (s *Store) MFAChallengeAttempt(token string, maxAttempts int) (*MFAChallenge, error) {
	h := hashSecret(token)
	now := time.Now().Unix()
	res, err := s.db.Exec(
		`UPDATE mfa_challenges SET attempts = attempts + 1 WHERE token=? AND expires_at >= ? AND attempts < ?`,
		h, now, maxAttempts)
	if err != nil {
		return nil, err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		_ = s.DeleteMFAChallenge(token)
		return nil, nil
	}
	var c MFAChallenge
	err = s.db.QueryRow(`SELECT user_id, kind, attempts FROM mfa_challenges WHERE token=?`, h).
		Scan(&c.UserID, &c.Kind, &c.Attempts)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &c, nil
}

// PeekMFAChallenge returns a live challenge without counting an attempt (for
// steps that check no code, like showing the setup QR), or nil.
func (s *Store) PeekMFAChallenge(token string) (*MFAChallenge, error) {
	var c MFAChallenge
	err := s.db.QueryRow(
		`SELECT user_id, kind, attempts FROM mfa_challenges WHERE token=? AND expires_at >= ?`,
		hashSecret(token), time.Now().Unix()).Scan(&c.UserID, &c.Kind, &c.Attempts)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &c, nil
}

// DeleteMFAChallenge removes a challenge (used up or abandoned).
func (s *Store) DeleteMFAChallenge(token string) error {
	_, err := s.db.Exec(`DELETE FROM mfa_challenges WHERE token=?`, hashSecret(token))
	return err
}

// DeleteMFAChallengesForUser removes a user's pending challenges (MFA reset).
func (s *Store) DeleteMFAChallengesForUser(userID int64) error {
	_, err := s.db.Exec(`DELETE FROM mfa_challenges WHERE user_id=?`, userID)
	return err
}
